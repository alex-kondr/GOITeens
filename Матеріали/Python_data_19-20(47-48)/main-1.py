class Node:
    def __init__(self, name):
        self.name = name
        self.children = []

    def add_child(self, child_node):
        self.children.append(child_node)

def print_tree(node: Node, level=0):
    if node is None:
        return
    indent = "  " * level
    print(f"{indent}{node.name}")
    for child in node.children:
        print_tree(child, level + 1)

